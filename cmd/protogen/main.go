// Command protogen reads spec/commands.yaml and writes Go encoders.
// It understands a small YAML subset: lists of commands with scalar fields.
package main

import (
	"fmt"
	"os"
	"strconv"
	"strings"
)

type field struct {
	name, typ   string
	left, right uint
	konst       string
	rotated     bool
}

type command struct {
	name, direction string
	id              int
	fields          []field
}

func main() {
	path := "spec/commands.yaml"
	if len(os.Args) > 1 {
		path = os.Args[1]
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	cmds := parse(string(raw))
	fmt.Println("// Code generated by protogen. DO NOT EDIT.")
	fmt.Println("package gen")
	fmt.Println()
	fmt.Println(`import "github.com/xenomit/server/pkg/protocol/codec"`)
	fmt.Println()
	for _, c := range cmds {
		writeFn(c)
	}
	fmt.Fprintf(os.Stderr, "generated %d commands\n", len(cmds))
}

func writeFn(c command) {
	fmt.Printf("const %sID int16 = %d\n\n", c.name, c.id)
	if c.direction == "in" || c.direction == "both" {
		fmt.Printf("func Decode%s(frame []byte) (map[string]any, error) {\n", c.name)
		fmt.Printf("\tr, err := codec.NewReader(frame)\n\tif err != nil { return nil, err }\n")
		fmt.Printf("\tif r.ID != %sID { return nil, codec.ErrFrame }\n", c.name)
		fmt.Printf("\tout := map[string]any{}\n")
		for _, f := range c.fields {
			if strings.HasPrefix(f.name, "_") {
				fmt.Printf("\t_, _ = r.Read%s()\n", readMethod(f.typ))
				continue
			}
			fmt.Printf("\t%s, err := r.Read%s()\n\tif err != nil { return nil, err }\n", safe(f.name), readMethod(f.typ))
			if f.rotated {
				fmt.Printf("\tout[%q] = codec.Mix(%s, %d, %d)\n", f.name, safe(f.name), f.left, f.right)
			} else {
				fmt.Printf("\tout[%q] = %s\n", f.name, safe(f.name))
			}
		}
		fmt.Printf("\treturn out, nil\n}\n\n")
	}
}

func readMethod(typ string) string {
	switch typ {
	case "short":
		return "Int16"
	case "int":
		return "Int32"
	case "utf":
		return "UTF"
	case "bool":
		return "Bool"
	default:
		return "Int32"
	}
}

func safe(name string) string {
	if name == "type" {
		return "typ"
	}
	return name
}

func parse(src string) []command {
	var cmds []command
	var cur *command
	var fld *field
	for _, line := range strings.Split(src, "\n") {
		trim := strings.TrimSpace(line)
		if trim == "" || strings.HasPrefix(trim, "#") {
			continue
		}
		indent := len(line) - len(strings.TrimLeft(line, " "))
		if strings.HasPrefix(trim, "- name:") && indent <= 2 {
			if cur != nil {
				if fld != nil {
					cur.fields = append(cur.fields, *fld)
					fld = nil
				}
				cmds = append(cmds, *cur)
			}
			cur = &command{name: strings.TrimSpace(strings.TrimPrefix(trim, "- name:"))}
			continue
		}
		if cur == nil {
			continue
		}
		if strings.HasPrefix(trim, "- {") || strings.HasPrefix(trim, "-{") {
			if fld != nil {
				cur.fields = append(cur.fields, *fld)
			}
			fld = parseInline(trim)
			cur.fields = append(cur.fields, *fld)
			fld = nil
			continue
		}
		key, val, ok := strings.Cut(trim, ":")
		if !ok {
			continue
		}
		key = strings.TrimSpace(key)
		val = strings.TrimSpace(val)
		switch key {
		case "id":
			cur.id, _ = strconv.Atoi(val)
		case "direction":
			cur.direction = val
		}
	}
	if cur != nil {
		cmds = append(cmds, *cur)
	}
	return cmds
}

func parseInline(trim string) *field {
	trim = strings.TrimPrefix(trim, "-")
	trim = strings.TrimSpace(trim)
	trim = strings.Trim(trim, "{}")
	f := &field{}
	for _, part := range strings.Split(trim, ",") {
		k, v, ok := strings.Cut(part, ":")
		if !ok {
			continue
		}
		k = strings.TrimSpace(k)
		v = strings.TrimSpace(v)
		switch k {
		case "name":
			f.name = v
		case "type":
			f.typ = v
		case "left":
			n, _ := strconv.Atoi(v)
			f.left = uint(n)
			f.rotated = true
		case "right":
			n, _ := strconv.Atoi(v)
			f.right = uint(n)
			f.rotated = true
		case "const":
			f.konst = v
		}
	}
	return f
}
