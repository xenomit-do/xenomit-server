-- Darkobit server schema ported from MySQL/MariaDB to PostgreSQL.
-- DDL only; no seed data.

CREATE TABLE chat_permissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL,
  type integer NOT NULL
);

CREATE INDEX idx_chat_permissions_user_id ON chat_permissions ("userId");

CREATE TABLE log_event_jpb (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  players jsonb NOT NULL DEFAULT '[]'::jsonb,
  finalists jsonb NOT NULL DEFAULT '[]'::jsonb,
  winner_id integer NOT NULL,
  start_date timestamp NOT NULL,
  end_date timestamp NOT NULL
);

CREATE TABLE log_player_kills (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  killer_id integer NOT NULL,
  target_id integer NOT NULL,
  pushing boolean NOT NULL,
  date_added timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_log_player_kills_killer_id ON log_player_kills (killer_id);
CREATE INDEX idx_log_player_kills_target_id ON log_player_kills (target_id);

CREATE TABLE player_accounts (
  "userId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "sessionId" varchar(32) NOT NULL,
  data jsonb NOT NULL DEFAULT '{"uridium":0,"credits":0,"honor":0,"experience":0,"jackpot":0}'::jsonb,
  "bootyKeys" jsonb NOT NULL DEFAULT '{"greenKeys": 0, "redKeys": 0, "blueKeys": 0}'::jsonb,
  info jsonb NOT NULL DEFAULT '{}'::jsonb,
  destructions jsonb NOT NULL DEFAULT '{"fpd":0,"dbrz":0}'::jsonb,
  username varchar(20) NOT NULL,
  "pilotName" varchar(20) NOT NULL,
  "petName" varchar(20) NOT NULL DEFAULT 'P.E.T 15',
  password varchar(255) NOT NULL,
  email varchar(260) NOT NULL,
  "shipId" integer NOT NULL DEFAULT 10,
  premium boolean NOT NULL DEFAULT false,
  title varchar(128) NOT NULL DEFAULT '',
  "factionId" smallint NOT NULL DEFAULT 0,
  "clanId" integer NOT NULL DEFAULT 0,
  "rankId" smallint NOT NULL DEFAULT 1,
  "rankPoints" bigint NOT NULL DEFAULT 0,
  rank integer NOT NULL DEFAULT 0,
  "warPoints" bigint NOT NULL DEFAULT 0,
  "warRank" integer DEFAULT 0,
  "extraEnergy" integer NOT NULL DEFAULT 0,
  nanohull integer NOT NULL DEFAULT 0,
  verification jsonb NOT NULL DEFAULT '{}'::jsonb,
  "oldPilotNames" jsonb NOT NULL DEFAULT '[]'::jsonb,
  version smallint NOT NULL DEFAULT 1
);

CREATE INDEX idx_player_accounts_session_id ON player_accounts ("sessionId");
CREATE INDEX idx_player_accounts_clan_id ON player_accounts ("clanId");
CREATE INDEX idx_player_accounts_username ON player_accounts (username);

