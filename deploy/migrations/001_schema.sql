CREATE TABLE player_titles (
  "userID" integer NOT NULL PRIMARY KEY,
  titles jsonb NOT NULL DEFAULT '[]'::jsonb
);

CREATE TABLE server_bans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL,
  "modId" integer NOT NULL,
  reason text NOT NULL,
  "typeId" smallint NOT NULL,
  ended boolean NOT NULL,
  end_date timestamp NOT NULL,
  date_added timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_server_bans_user_id ON server_bans ("userId");

CREATE TABLE server_battlestations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  "mapId" integer NOT NULL,
  "clanId" integer NOT NULL,
  "positionX" integer NOT NULL,
  "positionY" integer NOT NULL,
  "inBuildingState" smallint NOT NULL,
  "buildTimeInMinutes" integer NOT NULL,
  "buildTime" timestamp NOT NULL,
  "deflectorActive" smallint NOT NULL,
  "deflectorSecondsLeft" integer NOT NULL,
  "deflectorTime" timestamp NOT NULL,
  "visualModifiers" jsonb NOT NULL DEFAULT '[]'::jsonb,
  modules jsonb NOT NULL DEFAULT '[]'::jsonb,
  active smallint NOT NULL
);

CREATE INDEX idx_server_battlestations_map_id ON server_battlestations ("mapId");
CREATE INDEX idx_server_battlestations_clan_id ON server_battlestations ("clanId");

CREATE TABLE server_clans (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(50) NOT NULL DEFAULT '',
  tag varchar(4) NOT NULL DEFAULT '',
  description varchar(16000) NOT NULL DEFAULT '',
  "factionId" smallint NOT NULL DEFAULT 0,
  recruiting smallint NOT NULL DEFAULT 1,
  "leaderId" integer NOT NULL DEFAULT 0,
  news jsonb NOT NULL DEFAULT '[]'::jsonb,
  join_dates jsonb NOT NULL DEFAULT '{}'::jsonb,
  "rankPoints" bigint DEFAULT 0,
  rank integer NOT NULL DEFAULT 0,
  date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  profile varchar(255) NOT NULL DEFAULT 'default.jpg'
);

CREATE TABLE server_clan_applications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "clanId" integer NOT NULL,
  "userId" integer NOT NULL,
  text varchar(255) NOT NULL,
  date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_server_clan_applications_clan_id ON server_clan_applications ("clanId");
CREATE INDEX idx_server_clan_applications_user_id ON server_clan_applications ("userId");

CREATE TABLE server_clan_diplomacy (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "senderClanId" integer NOT NULL,
  "toClanId" integer NOT NULL,
  "diplomacyType" smallint NOT NULL,
  date timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_server_clan_diplomacy_sender ON server_clan_diplomacy ("senderClanId");
CREATE INDEX idx_server_clan_diplomacy_to ON server_clan_diplomacy ("toClanId");

CREATE TABLE server_clan_diplomacy_applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "senderClanId" integer NOT NULL,
  "toClanId" integer NOT NULL,
  "diplomacyType" smallint NOT NULL,
  date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_server_clan_diplomacy_apps_sender ON server_clan_diplomacy_applications ("senderClanId");
CREATE INDEX idx_server_clan_diplomacy_apps_to ON server_clan_diplomacy_applications ("toClanId");

CREATE TABLE server_maps (
  "mapID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL DEFAULT '',
  npcs jsonb NOT NULL DEFAULT '[]'::jsonb,
  stations jsonb NOT NULL DEFAULT '[]'::jsonb,
  portals jsonb NOT NULL DEFAULT '[]'::jsonb,
  collectables jsonb NOT NULL DEFAULT '[]'::jsonb,
  options jsonb NOT NULL DEFAULT '{"StarterMap":false,"PvpMap":false,"RangeDisabled":false,"CloakBlocked":false,"LogoutBlocked":false,"DeathLocationRepair":true}'::jsonb,
  "factionID" smallint NOT NULL DEFAULT 0
);

CREATE TABLE server_ships (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "shipID" integer NOT NULL,
  "baseShipId" integer NOT NULL,
  "lootID" varchar(255) NOT NULL DEFAULT '',
  name varchar(255) NOT NULL DEFAULT '',
  health integer NOT NULL DEFAULT 0,
  shield integer NOT NULL DEFAULT 0,
  speed integer NOT NULL DEFAULT 300,
  lasers integer NOT NULL DEFAULT 1,
  generators integer NOT NULL DEFAULT 1,
  cargo integer NOT NULL DEFAULT 100,
  aggressive boolean NOT NULL DEFAULT false,
  damage integer NOT NULL DEFAULT 20,
  respawnable boolean NOT NULL,
  reward jsonb NOT NULL DEFAULT '{"Experience":0,"Honor":0,"Credits":0,"Uridium":0}'::jsonb,
  CONSTRAINT server_ships_ship_id_unique UNIQUE ("shipID")
);

